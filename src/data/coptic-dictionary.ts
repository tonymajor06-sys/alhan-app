// ---- Pieces of a word: what comes before a word (ⲁϥ-, ⲙⲁⲣⲉⲛ-, ⲛⲓ-) and the "me, you, him" at its end ----

export interface Affix {
  // Written without jinkims, as the words are compared
  form: string;
  en: string;
  ar: string;
  // Who does it (ⲁϥ, ⲥⲉ, ⲙⲁⲣⲉⲛ…): only at the start of a word, or after "who" (ⲛⲏⲉⲧ-ⲁⲩ-ⲉⲛⲕⲟⲧ)
  doer?: boolean;
  // "who, which" (ⲉⲧ, ⲛⲏⲉⲧ…), which a doer may follow
  who?: boolean;
  // "the, a, my…": never two in a row, and the word after one takes no "me, him…" at its end
  the?: boolean;
  // ⲙ̀, ⲛ̀, ⲉ̀ (of, to): only at the very start of a word
  first?: boolean;
}

