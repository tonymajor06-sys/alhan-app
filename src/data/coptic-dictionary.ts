const who = (form: string, en: string, ar: string): Affix => ({ form, en, ar, who: true });
const the = (form: string, en: string, ar: string): Affix => ({ form, en, ar, the: true });
const first = (form: string, en: string, ar: string): Affix => ({ form, en, ar, first: true });

