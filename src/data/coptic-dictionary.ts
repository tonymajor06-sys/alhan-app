// More Bohairic words for the Coptic translator: the words of the app's hymns that the lessons don't teach, chosen by how
// often they occur in the hymns (2026-11-03). Each was checked against the Comprehensive Coptic Lexicon (BBAW/KELLIA,
// coptic-dictionary.org; mostly through the Sahidic form, e.g. ⲧⲁⲗϭⲟ "heal", ⲕⲁⲗⲁⲙⲫⲟ "hill") and against the app's own
// translations of the verses that use it (e.g. ⲉ̀ⲧⲉⲛϩⲟⲧ "faithful", ⲛⲉϫⲓ "womb"). Spelled as the hymns spell them.
// Sounds are worked out from the app's alphabet chart, unless written here (for shortened words like ⲡ̅ⲭ̅ⲥ̅).

export interface DictionaryWord {
  coptic: string;
  meaning: { en: string; ar: string };
  sound?: string;
  // Shortened spellings (ⲡ̅ⲭ̅ⲥ̅) and Greek words get a note in the results
  note?: { en: string; ar: string };
}

const w = (coptic: string, en: string, ar: string, sound?: string): DictionaryWord => ({ coptic, meaning: { en, ar }, sound });
const greek = (coptic: string, en: string, ar: string): DictionaryWord => ({
  coptic,
  meaning: { en, ar },
  note: { en: 'Greek, as the hymns use it', ar: 'كلمة يونانية كما تستخدمها الألحان' },
});
const short = (coptic: string, sound: string, en: string, ar: string, full: string): DictionaryWord => ({
  coptic,
  sound,
  meaning: { en, ar },
  note: { en: `Short for ${full}`, ar: `اختصار ${full}` },
});

